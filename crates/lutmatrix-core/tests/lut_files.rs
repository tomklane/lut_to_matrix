//! LUT file loading through real paths (spaces, non-ASCII names, extension case),
//! plus an optional check over a folder of real LUTs.

use std::path::PathBuf;

use lutmatrix_core::detect::detect;
use lutmatrix_core::lut::{write_cube, Interpolation, Lut, Lut3D};
use lutmatrix_core::math::Vec3;

fn tmp_dir(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("lutmatrix-test-{name}-{}", std::process::id()));
    std::fs::create_dir_all(&d).unwrap();
    d
}

#[test]
fn loads_paths_with_spaces_unicode_and_uppercase_extension() {
    let dir = tmp_dir("paths").join("Show LUTs (Ünïcode) – v2");
    std::fs::create_dir_all(&dir).unwrap();
    let lut = Lut3D::from_fn(9, |v| Vec3::new(v.x * 0.9, v.y * 0.8 + 0.1, v.z));
    let body = write_cube(&lut, "LogC4 to Rec709 test", &["Generated by lutmatrix tests"]);
    for name in ["My LUT LogC4_Rec709.cube", "Ärger LogC4 Rec709.CUBE", "x.Cube"] {
        let p = dir.join(name);
        std::fs::write(&p, &body).unwrap();
        let l = Lut::load(&p).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert_eq!(l.filename.as_deref(), Some(name));
        assert_eq!(l.title.as_deref(), Some("LogC4 to Rec709 test"));
        let o = l.apply(&Vec3::new(0.5, 0.5, 0.5), Interpolation::Tetrahedral);
        assert!((o - Vec3::new(0.45, 0.5, 0.5)).abs().max() < 1e-9);
    }
    let _ = std::fs::remove_dir_all(dir.parent().unwrap());
}

#[test]
fn missing_file_is_a_clear_error() {
    let e = Lut::load(&PathBuf::from("/definitely/not/here.cube")).unwrap_err();
    assert!(e.to_string().contains("could not read"));
}

/// Set LUTMATRIX_SAMPLE_LUTS to a folder of real LUTs to check they all parse and
/// get a detection (real LUTs are not committed to the repo).
#[test]
fn optional_real_lut_folder() {
    let Ok(dir) = std::env::var("LUTMATRIX_SAMPLE_LUTS") else { return };
    let mut n = 0;
    for e in std::fs::read_dir(dir).unwrap().flatten() {
        let p = e.path();
        let ext = p.extension().map(|x| x.to_string_lossy().to_lowercase());
        if !matches!(ext.as_deref(), Some("cube") | Some("3dl")) {
            continue;
        }
        let lut = Lut::load(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()));
        let _ = detect(&lut);
        n += 1;
    }
    assert!(n > 0, "no LUTs found");
}
