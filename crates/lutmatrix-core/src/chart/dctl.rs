//! The chart correction as a DaVinci Resolve DCTL (DWG / DaVinci Intermediate in and
//! out), in the same form as the LUT matrices (DECISIONS.md D21): explicit DWG_TO_XYZ,
//! M_XYZ and XYZ_TO_DWG, an Amount slider, and for the tone model a per-channel curve in
//! linear DWG before the matrix.

use std::fmt::Write as _;

use super::fit::{ChartFit, TONE_TOE};
use crate::dctl::{c, lit, matrix_fn};
use crate::spaces::curves::{DI_A, DI_B, DI_C, DI_LIN_CUT, DI_LOG_CUT, DI_M};
use crate::spaces::davinci;

/// Header text for a chart DCTL.
#[derive(Debug, Clone)]
pub struct ChartMeta {
    pub source_image: String,
    pub image_space: String,
    pub target: String,
    pub model: String,
    pub exposure: String,
    pub fit_error: String,
    pub version: String,
    pub date: String,
}

pub fn chart_dctl(fit: &ChartFit, meta: &ChartMeta) -> String {
    let mut s = String::new();
    let w = &mut s;
    let _ = writeln!(w, "// ============================================================================");
    let _ = writeln!(w, "// LUT Matrix - chart correction (3x3 matrix in linear CIE XYZ{})", if fit.tone.is_some() { " + tone curve" } else { "" });
    let _ = writeln!(w, "// ----------------------------------------------------------------------------");
    let _ = writeln!(w, "// Chart still:   {}", c(&meta.source_image));
    let _ = writeln!(w, "// Still encoded: {}", c(&meta.image_space));
    let _ = writeln!(w, "// Target:        {}", c(&meta.target));
    let _ = writeln!(w, "// Model:         {}", c(&meta.model));
    let _ = writeln!(w, "// Exposure:      {}", c(&meta.exposure));
    let _ = writeln!(w, "// Fit error:     {}", c(&meta.fit_error));
    let _ = writeln!(w, "// Generated by:  LUT Matrix {} on {} (UTC)", c(&meta.version), c(&meta.date));
    let _ = writeln!(w, "// ----------------------------------------------------------------------------");
    let _ = writeln!(w, "// Input and output: DaVinci Wide Gamut / DaVinci Intermediate. Apply it to");
    let _ = writeln!(w, "// footage from the same camera, decoded the same way as the chart still, in a");
    let _ = writeln!(w, "// DWG/DI timeline, before the output transform.");
    if fit.tone.is_some() {
        let _ = writeln!(w, "// Pipeline: DI -> linear DWG -> per-channel tone curve -> XYZ (DWG_TO_XYZ) ->");
        let _ = writeln!(w, "// M_XYZ -> blended with the input by 'Amount' -> linear DWG (XYZ_TO_DWG) -> DI.");
    } else {
        let _ = writeln!(w, "// Pipeline: DI -> linear DWG -> XYZ (DWG_TO_XYZ) -> M_XYZ (blended by 'Amount')");
        let _ = writeln!(w, "// -> linear DWG (XYZ_TO_DWG) -> DI.");
    }
    let _ = writeln!(w, "//");
    let _ = writeln!(w, "// DWG primaries R(0.8000, 0.3130) G(0.1682, 0.9877) B(0.0790, -0.1155), white");
    let _ = writeln!(w, "// D65 (0.3127, 0.3290), and the DaVinci Intermediate constants are from");
    let _ = writeln!(w, "// Blackmagic Design, \"DaVinci Wide Gamut Intermediate\" v1.1 (2021-07-31).");
    let _ = writeln!(w, "// ============================================================================");
    let _ = writeln!(w);
    let _ = writeln!(w, "DEFINE_UI_PARAMS(p_Amount, Amount, DCTLUI_SLIDER_FLOAT, 1.0, 0.0, 1.0, 0.001)");
    let _ = writeln!(w);
    let _ = writeln!(w, "typedef struct");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    float3 r0, r1, r2; // rows");
    let _ = writeln!(w, "}} Mat3x3;");
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float3 mat_mul(Mat3x3 m, float3 v)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    return make_float3(m.r0.x * v.x + m.r0.y * v.y + m.r0.z * v.z,");
    let _ = writeln!(w, "                       m.r1.x * v.x + m.r1.y * v.y + m.r1.z * v.z,");
    let _ = writeln!(w, "                       m.r2.x * v.x + m.r2.y * v.y + m.r2.z * v.z);");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    matrix_fn(w, "DWG_TO_XYZ", "Linear DaVinci Wide Gamut -> CIE XYZ (D65).", &davinci::dwg_to_xyz());
    matrix_fn(w, "M_XYZ", "Chart correction in linear CIE XYZ (D65): XYZ in -> XYZ out.", &fit.m_xyz);
    matrix_fn(w, "XYZ_TO_DWG", "CIE XYZ (D65) -> linear DaVinci Wide Gamut.", &davinci::xyz_to_dwg());
    let _ = writeln!(w, "// DaVinci Intermediate (Blackmagic, DWG Intermediate v1.1).");
    for (k, v) in [("DI_A", DI_A), ("DI_B", DI_B), ("DI_C", DI_C), ("DI_M", DI_M), ("DI_LIN_CUT", DI_LIN_CUT), ("DI_LOG_CUT", DI_LOG_CUT)] {
        let _ = writeln!(w, "#define {k:<11} {}", lit(v));
    }
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float di_to_linear(float v)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    if (v <= DI_LOG_CUT) return v / DI_M;");
    let _ = writeln!(w, "    return _powf(2.0f, v / DI_C - DI_B) - DI_A;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float linear_to_di(float l)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    if (l <= DI_LIN_CUT) return l * DI_M;");
    let _ = writeln!(w, "    return (_log2f(l + DI_A) + DI_B) * DI_C;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    if let Some(t) = &fit.tone {
        let _ = writeln!(w, "// Tone curve per channel in linear DWG: 0.18 * ((x - black) / 0.18)^power,");
        let _ = writeln!(w, "// continued below TONE_TOE by its tangent line (monotonic, finite for x < 0).");
        let _ = writeln!(w, "#define TONE_TOE    {}", lit(TONE_TOE));
        for (k, ch) in ["R", "G", "B"].iter().enumerate() {
            let _ = writeln!(w, "#define TONE_P_{ch}    {}", lit(t.power[k]));
            let _ = writeln!(w, "#define TONE_B_{ch}    {}", lit(t.black[k]));
        }
        let _ = writeln!(w);
        let _ = writeln!(w, "__DEVICE__ float tone(float x, float p, float b)");
        let _ = writeln!(w, "{{");
        let _ = writeln!(w, "    float t = x - b;");
        let _ = writeln!(w, "    if (t >= TONE_TOE) return 0.18f * _powf(t / 0.18f, p);");
        let _ = writeln!(w, "    float y0 = 0.18f * _powf(TONE_TOE / 0.18f, p);");
        let _ = writeln!(w, "    return y0 + p * y0 / TONE_TOE * (t - TONE_TOE);");
        let _ = writeln!(w, "}}");
        let _ = writeln!(w);
    }
    let _ = writeln!(w, "__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    // DaVinci Intermediate -> linear DaVinci Wide Gamut -> XYZ");
    let _ = writeln!(w, "    float3 dwg = make_float3(di_to_linear(p_R), di_to_linear(p_G), di_to_linear(p_B));");
    let _ = writeln!(w, "    float3 xyz = mat_mul(DWG_TO_XYZ(), dwg);");
    let _ = writeln!(w);
    if fit.tone.is_some() {
        let _ = writeln!(w, "    // Tone curve, then the matrix");
        let _ = writeln!(w, "    float3 toned = make_float3(tone(dwg.x, TONE_P_R, TONE_B_R), tone(dwg.y, TONE_P_G, TONE_B_G), tone(dwg.z, TONE_P_B, TONE_B_B));");
        let _ = writeln!(w, "    float3 fit = mat_mul(M_XYZ(), mat_mul(DWG_TO_XYZ(), toned));");
    } else {
        let _ = writeln!(w, "    // The matrix");
        let _ = writeln!(w, "    float3 fit = mat_mul(M_XYZ(), xyz);");
    }
    let _ = writeln!(w, "    // Blend with the input (p_Amount = 0 is a no-op)");
    let _ = writeln!(w, "    xyz = make_float3(xyz.x + (fit.x - xyz.x) * p_Amount,");
    let _ = writeln!(w, "                      xyz.y + (fit.y - xyz.y) * p_Amount,");
    let _ = writeln!(w, "                      xyz.z + (fit.z - xyz.z) * p_Amount);");
    let _ = writeln!(w);
    let _ = writeln!(w, "    // XYZ -> linear DWG -> DaVinci Intermediate");
    let _ = writeln!(w, "    dwg = mat_mul(XYZ_TO_DWG(), xyz);");
    let _ = writeln!(w, "    return make_float3(linear_to_di(dwg.x), linear_to_di(dwg.y), linear_to_di(dwg.z));");
    let _ = writeln!(w, "}}");
    debug_assert!(s.is_ascii());
    s
}

/// Suggested file name: "<image stem>_Chart.dctl", safe on Windows and macOS.
pub fn chart_dctl_file_name(image_name: &str) -> String {
    let stem = image_name.rsplit_once('.').map(|(a, _)| a).unwrap_or(image_name);
    let safe: String = stem.chars().map(|ch| if ch.is_alphanumeric() || "-_.".contains(ch) { ch } else { '_' }).collect();
    format!("{}_Chart.dctl", if safe.is_empty() { "Chart".into() } else { safe })
}
