//! The chart correction as a DaVinci Resolve DCTL (DWG / DaVinci Intermediate in and
//! out), in the same form as the LUT matrices (DECISIONS.md D21): explicit DWG_TO_XYZ,
//! M_XYZ and XYZ_TO_DWG, an Amount slider, and for the tone model a per-channel curve in
//! linear DWG before the matrix. The correction is split into a white balance (a
//! checkbox) and the matrix after it, optionally with highlight protection and its own
//! sliders (DECISIONS.md D42, [`super::highlights`]).

use std::fmt::Write as _;

use super::fit::{ChartFit, Model, TONE_TOE};
use super::highlights::{ClipSource, Highlights, CLIP_DI_RANGE, SOFTNESS_RANGE};
use super::tps::Tps;
use crate::dctl::{c, lit, matrix_fn};
use crate::spaces::curves::{DI_A, DI_B, DI_C, DI_LIN_CUT, DI_LOG_CUT, DI_M};
use crate::spaces::davinci;

/// Header text for a chart DCTL.
#[derive(Debug, Clone)]
pub struct ChartMeta {
    pub source_image: String,
    pub image_space: String,
    pub target: String,
    pub model: String,
    pub exposure: String,
    pub fit_error: String,
    pub version: String,
    pub date: String,
}

pub fn chart_dctl(fit: &ChartFit, hl: &Highlights, white_balance: bool, meta: &ChartMeta) -> String {
    if let (Some(t), Model::Tps) = (&fit.tps, fit.settings.model) {
        return tps_dctl(t, fit.gray_dwg, hl, meta);
    }
    let mut s = String::new();
    let w = &mut s;
    let _ = writeln!(w, "// ============================================================================");
    let _ = writeln!(w, "// LUT Matrix - chart correction (3x3 matrix in linear CIE XYZ{})", if fit.tone.is_some() { " + tone curve" } else { "" });
    let _ = writeln!(w, "// ----------------------------------------------------------------------------");
    let _ = writeln!(w, "// Chart still:   {}", c(&meta.source_image));
    let _ = writeln!(w, "// Still encoded: {}", c(&meta.image_space));
    let _ = writeln!(w, "// Target:        {}", c(&meta.target));
    let _ = writeln!(w, "// Model:         {}", c(&meta.model));
    let _ = writeln!(w, "// Exposure:      {}", c(&meta.exposure));
    let _ = writeln!(w, "// Fit error:     {}", c(&meta.fit_error));
    let _ = writeln!(w, "// Generated by:  LUT Matrix {} on {} (UTC)", c(&meta.version), c(&meta.date));
    let _ = writeln!(w, "// ----------------------------------------------------------------------------");
    let _ = writeln!(w, "// Input and output: DaVinci Wide Gamut / DaVinci Intermediate. Apply it to");
    let _ = writeln!(w, "// footage from the same camera, decoded the same way as the chart still, in a");
    let _ = writeln!(w, "// DWG/DI timeline, before the output transform.");
    let _ = writeln!(w, "// Pipeline: DI -> linear DWG -> {}{}white balance (gains in linear DWG,", if hl.enabled { "highlight protection -> " } else { "" }, if fit.tone.is_some() { "per-channel tone curve -> " } else { "" });
    let _ = writeln!(w, "// skipped when 'WB Done In Raw' is ticked) -> XYZ (DWG_TO_XYZ) -> M_XYZ -> blended");
    let _ = writeln!(w, "// {}with the input by 'Amount' -> linear DWG (XYZ_TO_DWG) -> DI.", if fit.tps.is_some() { "-> TPS3D (colour only, in DI DWG) -> " } else { "" });
    let _ = writeln!(w, "//");
    let [gr, _, gb] = fit.wb_gains;
    let _ = writeln!(w, "// White balance: R x{gr:.4}, G x1, B x{gb:.4} make the chart's gray neutral. Tick");
    let _ = writeln!(w, "// 'WB Done In Raw' for footage white-balanced in the raw decode (only the matrix");
    let _ = writeln!(w, "// runs then). Unticked (also what Resolve gives a new checkbox) = the full correction.");
    if hl.enabled {
        let src = match hl.source {
            ClipSource::Set => "set by hand".to_string(),
            ClipSource::Measured => "measured in the chart still".to_string(),
            ClipSource::Brightest => "the chart still's brightest value (it doesn't clip): set it to where the footage clips".to_string(),
            ClipSource::Default => "a typical value (the still says nothing): set it to where the footage clips".to_string(),
        };
        let _ = writeln!(w, "//");
        let _ = writeln!(w, "// Highlight protection: each channel within 'Highlight Softness' stops of");
        let _ = writeln!(w, "// 'Highlight Clip DI' is raised towards the camera's white (the chart's gray with");
        let _ = writeln!(w, "// the white balance on, equal RGB with 'WB Done In Raw'), so clipped areas come out white");
        let _ = writeln!(w, "// instead of the colour the correction would give them.");
        let _ = writeln!(w, "// Clip level {:.4} DI: {}.", hl.clip_di, c(&src));
    }
    let _ = writeln!(w, "//");
    let _ = writeln!(w, "// DWG primaries R(0.8000, 0.3130) G(0.1682, 0.9877) B(0.0790, -0.1155), white");
    let _ = writeln!(w, "// D65 (0.3127, 0.3290), and the DaVinci Intermediate constants are from");
    let _ = writeln!(w, "// Blackmagic Design, \"DaVinci Wide Gamut Intermediate\" v1.1 (2021-07-31).");
    let _ = writeln!(w, "// ============================================================================");
    let _ = writeln!(w);
    let _ = writeln!(w, "DEFINE_UI_PARAMS(p_Amount, Amount, DCTLUI_SLIDER_FLOAT, 1.0, 0.0, 1.0, 0.001)");
    let _ = writeln!(w, "DEFINE_UI_PARAMS(p_RawWB, WB Done In Raw, DCTLUI_CHECK_BOX, {})", u8::from(!white_balance));
    if hl.enabled {
        let f = |v: f64| format!("{v:.4}");
        let _ = writeln!(w, "DEFINE_UI_PARAMS(p_HlProtect, Highlight Protection, DCTLUI_SLIDER_FLOAT, {}, 0.0, 1.0, 0.01)", f(hl.strength));
        let _ = writeln!(
            w,
            "DEFINE_UI_PARAMS(p_HlClip, Highlight Clip DI, DCTLUI_SLIDER_FLOAT, {}, {}, {}, 0.001)",
            f(hl.clip_di),
            f(CLIP_DI_RANGE.0),
            f(CLIP_DI_RANGE.1)
        );
        let _ = writeln!(
            w,
            "DEFINE_UI_PARAMS(p_HlSoft, Highlight Softness, DCTLUI_SLIDER_FLOAT, {}, {}, {}, 0.05)",
            f(hl.softness),
            f(SOFTNESS_RANGE.0),
            f(SOFTNESS_RANGE.1)
        );
    }
    let _ = writeln!(w);
    let _ = writeln!(w, "typedef struct");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    float3 r0, r1, r2; // rows");
    let _ = writeln!(w, "}} Mat3x3;");
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float3 mat_mul(Mat3x3 m, float3 v)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    return make_float3(m.r0.x * v.x + m.r0.y * v.y + m.r0.z * v.z,");
    let _ = writeln!(w, "                       m.r1.x * v.x + m.r1.y * v.y + m.r1.z * v.z,");
    let _ = writeln!(w, "                       m.r2.x * v.x + m.r2.y * v.y + m.r2.z * v.z);");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    matrix_fn(w, "DWG_TO_XYZ", "Linear DaVinci Wide Gamut -> CIE XYZ (D65).", &davinci::dwg_to_xyz());
    matrix_fn(w, "M_XYZ", "Chart correction after the white balance, linear CIE XYZ (D65): XYZ in -> XYZ out.", &fit.m_xyz_after_wb);
    matrix_fn(w, "XYZ_TO_DWG", "CIE XYZ (D65) -> linear DaVinci Wide Gamut.", &davinci::xyz_to_dwg());
    let _ = writeln!(w, "// White balance gains in linear DWG (after the tone curve, if any).");
    for (k, ch) in ["R", "G", "B"].iter().enumerate() {
        let _ = writeln!(w, "#define WB_{ch}        {}", lit(fit.wb_gains[k]));
    }
    let _ = writeln!(w);
    let _ = writeln!(w, "// DaVinci Intermediate (Blackmagic, DWG Intermediate v1.1).");
    for (k, v) in [("DI_A", DI_A), ("DI_B", DI_B), ("DI_C", DI_C), ("DI_M", DI_M), ("DI_LIN_CUT", DI_LIN_CUT), ("DI_LOG_CUT", DI_LOG_CUT)] {
        let _ = writeln!(w, "#define {k:<11} {}", lit(v));
    }
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float di_to_linear(float v)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    if (v <= DI_LOG_CUT) return v / DI_M;");
    let _ = writeln!(w, "    return _powf(2.0f, v / DI_C - DI_B) - DI_A;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float linear_to_di(float l)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    if (l <= DI_LIN_CUT) return l * DI_M;");
    let _ = writeln!(w, "    return (_log2f(l + DI_A) + DI_B) * DI_C;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    if hl.enabled {
        let g = fit.gray_dwg;
        let ok = g.iter().all(|v| v.is_finite() && *v > 1e-6);
        let _ = writeln!(w, "// The camera's white in linear DWG (the chart's mid gray, green = 1).");
        let _ = writeln!(w, "#define CAM_WHITE_R {}", lit(if ok { g[0] } else { 1.0 }));
        let _ = writeln!(w, "#define CAM_WHITE_B {}", lit(if ok { g[2] } else { 1.0 }));
        let _ = writeln!(w);
        let _ = writeln!(w, "// One channel (linear DWG) raised towards 'est' by its highlight weight: smoothstep");
        let _ = writeln!(w, "// from 'soft' stops below the clip to the clip, times 'amount'.");
        let _ = writeln!(w, "__DEVICE__ float rebuild(float v, float est, float amount, float clip_di, float soft)");
        let _ = writeln!(w, "{{");
        let _ = writeln!(w, "    float lc = di_to_linear(clip_di);");
        let _ = writeln!(w, "    if (est <= v || amount <= 0.0f || v <= 0.0f || lc <= 0.0f) return v;");
        let _ = writeln!(w, "    float t = _log2f(v / lc) / _fmaxf(soft, 0.001f) + 1.0f;");
        let _ = writeln!(w, "    t = _fminf(_fmaxf(t, 0.0f), 1.0f);");
        let _ = writeln!(w, "    return v + t * t * (3.0f - 2.0f * t) * amount * (est - v);");
        let _ = writeln!(w, "}}");
        let _ = writeln!(w);
    }
    if let Some(t) = &fit.tone {
        let _ = writeln!(w, "// Tone curve per channel in linear DWG: 0.18 * ((x - black) / 0.18)^power,");
        let _ = writeln!(w, "// continued below TONE_TOE by its tangent line (monotonic, finite for x < 0).");
        let _ = writeln!(w, "#define TONE_TOE    {}", lit(TONE_TOE));
        for (k, ch) in ["R", "G", "B"].iter().enumerate() {
            let _ = writeln!(w, "#define TONE_P_{ch}    {}", lit(t.power[k]));
            let _ = writeln!(w, "#define TONE_B_{ch}    {}", lit(t.black[k]));
        }
        let _ = writeln!(w);
        let _ = writeln!(w, "__DEVICE__ float tone(float x, float p, float b)");
        let _ = writeln!(w, "{{");
        let _ = writeln!(w, "    float t = x - b;");
        let _ = writeln!(w, "    if (t >= TONE_TOE) return 0.18f * _powf(t / 0.18f, p);");
        let _ = writeln!(w, "    float y0 = 0.18f * _powf(TONE_TOE / 0.18f, p);");
        let _ = writeln!(w, "    return y0 + p * y0 / TONE_TOE * (t - TONE_TOE);");
        let _ = writeln!(w, "}}");
        let _ = writeln!(w);
    }
    if let Some(t) = &fit.tps {
        tps_defs(w, t);
    }
    let _ = writeln!(w, "__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    // DaVinci Intermediate -> linear DaVinci Wide Gamut -> XYZ");
    let _ = writeln!(w, "    float3 dwg = make_float3(di_to_linear(p_R), di_to_linear(p_G), di_to_linear(p_B));");
    let _ = writeln!(w, "    float3 xyz = mat_mul(DWG_TO_XYZ(), dwg);");
    let _ = writeln!(w);
    let mut cur = "dwg";
    if hl.enabled {
        let _ = writeln!(w, "    // Highlight protection: clipped channels towards the camera's white");
        let _ = writeln!(w, "    float3 cw = p_RawWB ? make_float3(1.0f, 1.0f, 1.0f) : make_float3(CAM_WHITE_R, 1.0f, CAM_WHITE_B);");
        let _ = writeln!(w, "    float sc = _fmaxf(dwg.x / cw.x, _fmaxf(dwg.y / cw.y, dwg.z / cw.z));");
        let _ = writeln!(w, "    float3 src = make_float3(rebuild(dwg.x, sc * cw.x, p_HlProtect, p_HlClip, p_HlSoft),");
        let _ = writeln!(w, "                             rebuild(dwg.y, sc * cw.y, p_HlProtect, p_HlClip, p_HlSoft),");
        let _ = writeln!(w, "                             rebuild(dwg.z, sc * cw.z, p_HlProtect, p_HlClip, p_HlSoft));");
        let _ = writeln!(w);
        cur = "src";
    }
    if fit.tone.is_some() {
        let _ = writeln!(w, "    // Tone curve");
        let _ = writeln!(
            w,
            "    float3 bal = make_float3(tone({cur}.x, TONE_P_R, TONE_B_R), tone({cur}.y, TONE_P_G, TONE_B_G), tone({cur}.z, TONE_P_B, TONE_B_B));"
        );
    } else {
        let _ = writeln!(w, "    float3 bal = {cur};");
    }
    let _ = writeln!(w, "    // White balance (not for footage already balanced in the raw decode)");
    let _ = writeln!(w, "    if (!p_RawWB) bal = make_float3(bal.x * WB_R, bal.y * WB_G, bal.z * WB_B);");
    let _ = writeln!(w, "    // The matrix");
    let _ = writeln!(w, "    float3 fit = mat_mul(M_XYZ(), mat_mul(DWG_TO_XYZ(), bal));");
    if let Some(t) = &fit.tps {
        let _ = writeln!(w, "    // TPS3D after the matrix: colour only, in DaVinci Intermediate DWG");
        let _ = writeln!(w, "    {{");
        let _ = writeln!(w, "        float3 sd = mat_mul(XYZ_TO_DWG(), fit);");
        let _ = writeln!(w, "        float3 d = make_float3(linear_to_di(sd.x), linear_to_di(sd.y), linear_to_di(sd.z));");
        tps_eval(w, t, "        ");
        let _ = writeln!(w, "        fit = mat_mul(DWG_TO_XYZ(), make_float3(di_to_linear(d.x), di_to_linear(d.y), di_to_linear(d.z)));");
        let _ = writeln!(w, "    }}");
    }
    let _ = writeln!(w, "    // Blend with the input (p_Amount = 0 is a no-op)");
    let _ = writeln!(w, "    xyz = make_float3(xyz.x + (fit.x - xyz.x) * p_Amount,");
    let _ = writeln!(w, "                      xyz.y + (fit.y - xyz.y) * p_Amount,");
    let _ = writeln!(w, "                      xyz.z + (fit.z - xyz.z) * p_Amount);");
    let _ = writeln!(w);
    let _ = writeln!(w, "    // XYZ -> linear DWG -> DaVinci Intermediate");
    let _ = writeln!(w, "    dwg = mat_mul(XYZ_TO_DWG(), xyz);");
    let _ = writeln!(w, "    return make_float3(linear_to_di(dwg.x), linear_to_di(dwg.y), linear_to_di(dwg.z));");
    let _ = writeln!(w, "}}");
    debug_assert!(s.is_ascii());
    s
}

fn header(w: &mut String, title: &str, meta: &ChartMeta) {
    let _ = writeln!(w, "// ============================================================================");
    let _ = writeln!(w, "// LUT Matrix - {title}");
    let _ = writeln!(w, "// ----------------------------------------------------------------------------");
    let _ = writeln!(w, "// Chart still:   {}", c(&meta.source_image));
    let _ = writeln!(w, "// Still encoded: {}", c(&meta.image_space));
    let _ = writeln!(w, "// Target:        {}", c(&meta.target));
    let _ = writeln!(w, "// Model:         {}", c(&meta.model));
    let _ = writeln!(w, "// Exposure:      {}", c(&meta.exposure));
    let _ = writeln!(w, "// Fit error:     {}", c(&meta.fit_error));
    let _ = writeln!(w, "// Generated by:  LUT Matrix {} on {} (UTC)", c(&meta.version), c(&meta.date));
    let _ = writeln!(w, "// ----------------------------------------------------------------------------");
    let _ = writeln!(w, "// Input and output: DaVinci Wide Gamut / DaVinci Intermediate. Apply it to");
    let _ = writeln!(w, "// footage from the same camera, decoded the same way as the chart still, in a");
    let _ = writeln!(w, "// DWG/DI timeline, before the output transform.");
}

fn di_functions(w: &mut String) {
    let _ = writeln!(w, "// DaVinci Intermediate (Blackmagic, DWG Intermediate v1.1).");
    for (k, v) in [("DI_A", DI_A), ("DI_B", DI_B), ("DI_C", DI_C), ("DI_M", DI_M), ("DI_LIN_CUT", DI_LIN_CUT), ("DI_LOG_CUT", DI_LOG_CUT)] {
        let _ = writeln!(w, "#define {k:<11} {}", lit(v));
    }
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float di_to_linear(float v)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    if (v <= DI_LOG_CUT) return v / DI_M;");
    let _ = writeln!(w, "    return _powf(2.0f, v / DI_C - DI_B) - DI_A;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "__DEVICE__ float linear_to_di(float l)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    if (l <= DI_LIN_CUT) return l * DI_M;");
    let _ = writeln!(w, "    return (_log2f(l + DI_A) + DI_B) * DI_C;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
}

fn highlight_params(w: &mut String, hl: &Highlights) {
    let f = |v: f64| format!("{v:.4}");
    let _ = writeln!(w, "DEFINE_UI_PARAMS(p_HlProtect, Highlight Protection, DCTLUI_SLIDER_FLOAT, {}, 0.0, 1.0, 0.01)", f(hl.strength));
    let _ = writeln!(
        w,
        "DEFINE_UI_PARAMS(p_HlClip, Highlight Clip DI, DCTLUI_SLIDER_FLOAT, {}, {}, {}, 0.001)",
        f(hl.clip_di),
        f(CLIP_DI_RANGE.0),
        f(CLIP_DI_RANGE.1)
    );
    let _ = writeln!(
        w,
        "DEFINE_UI_PARAMS(p_HlSoft, Highlight Softness, DCTLUI_SLIDER_FLOAT, {}, {}, {}, 0.05)",
        f(hl.softness),
        f(SOFTNESS_RANGE.0),
        f(SOFTNESS_RANGE.1)
    );
}

fn rebuild_fn(w: &mut String) {
    let _ = writeln!(w, "// One channel (linear DWG) raised towards 'est' by its highlight weight: smoothstep");
    let _ = writeln!(w, "// from 'soft' stops below the clip to the clip, times 'amount'.");
    let _ = writeln!(w, "__DEVICE__ float rebuild(float v, float est, float amount, float clip_di, float soft)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    float lc = di_to_linear(clip_di);");
    let _ = writeln!(w, "    if (est <= v || amount <= 0.0f || v <= 0.0f || lc <= 0.0f) return v;");
    let _ = writeln!(w, "    float t = _log2f(v / lc) / _fmaxf(soft, 0.001f) + 1.0f;");
    let _ = writeln!(w, "    t = _fminf(_fmaxf(t, 0.0f), 1.0f);");
    let _ = writeln!(w, "    return v + t * t * (3.0f - 2.0f * t) * amount * (est - v);");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
}

fn clip_source(hl: &Highlights) -> String {
    match hl.source {
        ClipSource::Set => "set by hand".to_string(),
        ClipSource::Measured => "measured in the chart still".to_string(),
        ClipSource::Brightest => "the chart still's brightest value (it doesn't clip): set it to where the footage clips".to_string(),
        ClipSource::Default => "a typical value (the still says nothing): set it to where the footage clips".to_string(),
    }
}

/// The TPS3D DCTL: the spline alone, no matrix (D44).
fn tps_dctl(t: &Tps, gray: [f64; 3], hl: &Highlights, meta: &ChartMeta) -> String {
    let mut s = String::new();
    let w = &mut s;
    header(w, "chart correction (TPS3D: gray curve + thin-plate spline, no matrix)", meta);
    let _ = writeln!(w, "// Pipeline: DI -> {}per-channel gray curve -> TPS3D with gray correction", if hl.enabled { "highlight protection (linear DWG) -> " } else { "" });
    let _ = writeln!(w, "// (both in DaVinci Intermediate DWG) -> blended with the input by 'Amount' -> DI.");
    let _ = writeln!(w, "//");
    let _ = writeln!(w, "// Gray balance curve: per channel, a monotone cubic through the chart's grays (each");
    let _ = writeln!(w, "// channel -> that gray's level), linear beyond the end grays, shifted back to the");
    let _ = writeln!(w, "// pixel's level. With the spline's targets at each patch's own level, TPS3D changes");
    let _ = writeln!(w, "// colour only: the mean of R, G, B (DI) of every pixel is kept.");
    let _ = writeln!(w, "// TPS3D: f(d) = A[k][0] + A[k][1..3] . d + sum_i W[i][k] * |d - C[i]| + d, kernel |r|");
    let _ = writeln!(w, "// (3D thin plate), {} control points (chart patches, synthetic neutrals and the DI", t.centres.len());
    let _ = writeln!(w, "// cube corners), smoothing {}. Gray correction: out = f(d) - (f(L,L,L) - (L,L,L)),", t.smoothing);
    let _ = writeln!(w, "// L = (d.r + d.g + d.b) / 3, so equal R, G, B (clipped white too) pass unchanged.");
    if hl.enabled {
        let _ = writeln!(w, "//");
        let _ = writeln!(w, "// Highlight protection: each channel within 'Highlight Softness' stops of");
        let _ = writeln!(w, "// 'Highlight Clip DI' is raised towards the camera's white (the chart's gray), which");
        let _ = writeln!(w, "// the gray curve makes neutral and the spline leaves alone: clipped areas go white.");
        let _ = writeln!(w, "// Clip level {:.4} DI: {}.", hl.clip_di, c(&clip_source(hl)));
    }
    let _ = writeln!(w, "//");
    let _ = writeln!(w, "// The DaVinci Intermediate constants are from Blackmagic Design, \"DaVinci Wide");
    let _ = writeln!(w, "// Gamut Intermediate\" v1.1 (2021-07-31).");
    let _ = writeln!(w, "// ============================================================================");
    let _ = writeln!(w);
    let _ = writeln!(w, "DEFINE_UI_PARAMS(p_Amount, Amount, DCTLUI_SLIDER_FLOAT, 1.0, 0.0, 1.0, 0.001)");
    if hl.enabled {
        highlight_params(w, hl);
    }
    let _ = writeln!(w);
    di_functions(w);
    if hl.enabled {
        let ok = gray.iter().all(|v| v.is_finite() && *v > 1e-6);
        let _ = writeln!(w, "// The camera's white in linear DWG (the chart's mid gray, green = 1).");
        let _ = writeln!(w, "#define CAM_WHITE_R {}", lit(if ok { gray[0] } else { 1.0 }));
        let _ = writeln!(w, "#define CAM_WHITE_B {}", lit(if ok { gray[2] } else { 1.0 }));
        let _ = writeln!(w);
        rebuild_fn(w);
    }
    tps_defs(w, t);
    let _ = writeln!(w, "__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)");
    let _ = writeln!(w, "{{");
    let _ = writeln!(w, "    float3 d = make_float3(p_R, p_G, p_B);");
    if hl.enabled {
        let _ = writeln!(w);
        let _ = writeln!(w, "    // Highlight protection: clipped channels towards the camera's white (linear DWG)");
        let _ = writeln!(w, "    float3 dwg = make_float3(di_to_linear(p_R), di_to_linear(p_G), di_to_linear(p_B));");
        let _ = writeln!(w, "    float sc = _fmaxf(dwg.x / CAM_WHITE_R, _fmaxf(dwg.y, dwg.z / CAM_WHITE_B));");
        let _ = writeln!(w, "    dwg = make_float3(rebuild(dwg.x, sc * CAM_WHITE_R, p_HlProtect, p_HlClip, p_HlSoft),");
        let _ = writeln!(w, "                      rebuild(dwg.y, sc, p_HlProtect, p_HlClip, p_HlSoft),");
        let _ = writeln!(w, "                      rebuild(dwg.z, sc * CAM_WHITE_B, p_HlProtect, p_HlClip, p_HlSoft));");
        let _ = writeln!(w, "    d = make_float3(linear_to_di(dwg.x), linear_to_di(dwg.y), linear_to_di(dwg.z));");
    }
    tps_eval(w, t, "    ");
    let _ = writeln!(w);
    let _ = writeln!(w, "    // Blend with the input (p_Amount = 0 is a no-op)");
    let _ = writeln!(w, "    return make_float3(p_R + (d.x - p_R) * p_Amount, p_G + (d.y - p_G) * p_Amount, p_B + (d.z - p_B) * p_Amount);");
    let _ = writeln!(w, "}}");
    debug_assert!(s.is_ascii());
    s
}

/// The TPS3D definitions: gray balance curves and the spline's points (D44, D45).
fn tps_defs(w: &mut String, t: &Tps) {
    if let Some(c) = &t.curve {
        let _ = writeln!(w, "// Cubic Hermite segment.");
        let _ = writeln!(w, "__DEVICE__ float herm(float v, float x0, float x1, float y0, float y1, float m0, float m1)");
        let _ = writeln!(w, "{{");
        let _ = writeln!(w, "    float h = x1 - x0, t = (v - x0) / h, t2 = t * t, t3 = t2 * t;");
        let _ = writeln!(w, "    return (2.0f * t3 - 3.0f * t2 + 1.0f) * y0 + (t3 - 2.0f * t2 + t) * h * m0 + (-2.0f * t3 + 3.0f * t2) * y1 + (t3 - t2) * h * m1;");
        let _ = writeln!(w, "}}");
        let _ = writeln!(w);
        for (k, ch) in ["r", "g", "b"].iter().enumerate() {
            let (x, y, m) = (&c.x[k], &c.y[k], &c.m[k]);
            let n = x.len();
            let _ = writeln!(w, "__DEVICE__ float gray_{ch}(float v)");
            let _ = writeln!(w, "{{");
            let _ = writeln!(w, "    if (v <= {}) return {} + {} * (v - {});", lit(x[0]), lit(y[0]), lit(m[0]), lit(x[0]));
            let _ = writeln!(w, "    if (v >= {}) return {} + {} * (v - {});", lit(x[n - 1]), lit(y[n - 1]), lit(m[n - 1]), lit(x[n - 1]));
            for i in 0..n - 1 {
                let _ = writeln!(
                    w,
                    "    if (v < {}) return herm(v, {}, {}, {}, {}, {}, {});",
                    lit(x[i + 1]),
                    lit(x[i]),
                    lit(x[i + 1]),
                    lit(y[i]),
                    lit(y[i + 1]),
                    lit(m[i]),
                    lit(m[i + 1])
                );
            }
            let _ = writeln!(w, "    return {};", lit(y[n - 1]));
            let _ = writeln!(w, "}}");
            let _ = writeln!(w);
        }
    }
    let n = t.centres.len();
    let flat = |v: &[[f64; 3]]| v.iter().flat_map(|p| p.iter().map(|x| lit(*x))).collect::<Vec<_>>().join(", ");
    let _ = writeln!(w, "#define TPS_N {n}");
    let _ = writeln!(w, "__CONSTANT__ float TPS_C[{}] = {{{}}};", 3 * n, flat(&t.centres));
    let _ = writeln!(w, "__CONSTANT__ float TPS_W[{}] = {{{}}};", 3 * n, flat(&t.weights));
    let aff: Vec<String> = t.affine.iter().flat_map(|r| r.iter().map(|x| lit(*x))).collect();
    let _ = writeln!(w, "__CONSTANT__ float TPS_A[12] = {{{}}};", aff.join(", "));
    let _ = writeln!(w);
}

/// TPS3D applied to the DI DWG vector `d` in place (indented by `i`).
fn tps_eval(w: &mut String, t: &Tps, i: &str) {
    if t.curve.is_some() {
        let _ = writeln!(w);
        let _ = writeln!(w, "{i}// Gray balance curve per channel, keeping the level (mean)");
        let _ = writeln!(w, "{i}float3 gc = make_float3(gray_r(d.x), gray_g(d.y), gray_b(d.z));");
        let _ = writeln!(w, "{i}float gk = (d.x + d.y + d.z - gc.x - gc.y - gc.z) / 3.0f;");
        let _ = writeln!(w, "{i}d = make_float3(gc.x + gk, gc.y + gk, gc.z + gk);");
    }
    let _ = writeln!(w);
    let _ = writeln!(w, "{i}// TPS3D residual at d and at the gray of the same level, L = mean(d)");
    let _ = writeln!(w, "{i}float L = (d.x + d.y + d.z) / 3.0f;");
    let _ = writeln!(w, "{i}float rx = TPS_A[1] * d.x + TPS_A[2] * d.y + TPS_A[3] * d.z;");
    let _ = writeln!(w, "{i}float ry = TPS_A[5] * d.x + TPS_A[6] * d.y + TPS_A[7] * d.z;");
    let _ = writeln!(w, "{i}float rz = TPS_A[9] * d.x + TPS_A[10] * d.y + TPS_A[11] * d.z;");
    let _ = writeln!(w, "{i}float nx = (TPS_A[1] + TPS_A[2] + TPS_A[3]) * L;");
    let _ = writeln!(w, "{i}float ny = (TPS_A[5] + TPS_A[6] + TPS_A[7]) * L;");
    let _ = writeln!(w, "{i}float nz = (TPS_A[9] + TPS_A[10] + TPS_A[11]) * L;");
    let _ = writeln!(w, "{i}for (int i = 0; i < TPS_N; i++) {{");
    let _ = writeln!(w, "{i}    float cx = TPS_C[3 * i], cy = TPS_C[3 * i + 1], cz = TPS_C[3 * i + 2];");
    let _ = writeln!(w, "{i}    float r = _sqrtf((d.x - cx) * (d.x - cx) + (d.y - cy) * (d.y - cy) + (d.z - cz) * (d.z - cz));");
    let _ = writeln!(w, "{i}    float q = _sqrtf((L - cx) * (L - cx) + (L - cy) * (L - cy) + (L - cz) * (L - cz));");
    let _ = writeln!(w, "{i}    rx += TPS_W[3 * i] * r;");
    let _ = writeln!(w, "{i}    ry += TPS_W[3 * i + 1] * r;");
    let _ = writeln!(w, "{i}    rz += TPS_W[3 * i + 2] * r;");
    let _ = writeln!(w, "{i}    nx += TPS_W[3 * i] * q;");
    let _ = writeln!(w, "{i}    ny += TPS_W[3 * i + 1] * q;");
    let _ = writeln!(w, "{i}    nz += TPS_W[3 * i + 2] * q;");
    let _ = writeln!(w, "{i}}}");
    let _ = writeln!(w, "{i}// Gray correction: f(d) - (f(L,L,L) - (L,L,L)); the constants cancel");
    let _ = writeln!(w, "{i}d = make_float3(d.x + rx - nx, d.y + ry - ny, d.z + rz - nz);");
}

/// Suggested file name: "<image stem>_Chart.dctl", safe on Windows and macOS.
pub fn chart_dctl_file_name(image_name: &str) -> String {
    let stem = image_name.rsplit_once('.').map(|(a, _)| a).unwrap_or(image_name);
    let safe: String = stem.chars().map(|ch| if ch.is_alphanumeric() || "-_.".contains(ch) { ch } else { '_' }).collect();
    format!("{}_Chart.dctl", if safe.is_empty() { "Chart".into() } else { safe })
}
