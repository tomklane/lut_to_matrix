//! Guess a LUT's input (camera log) and output (display) spaces.
//!
//! Evidence comes from the filename, the TITLE line and comments, scored with the
//! keyword tables in `spaces::camera` and below. Two cheap data checks add to it:
//! - **Gray probe:** each candidate camera space's 18% gray is pushed through the
//!   LUT; a candidate whose gray lands near display middle gray gains a little
//!   evidence. This catches e.g. a LogC4 LUT mislabelled LogC3 (≈1.6 stops apart).
//! - **Output range:** a LUT whose output never exceeds ~0.8 is likely PQ, and the
//!   peak it reaches estimates the PQ mastering peak.
//!
//! The result says how confident each guess is and why; the UI lets the user override.

use regex::Regex;
use serde::Serialize;

use crate::lut::{Interpolation, Lut};
use crate::math::Vec3;
use crate::spaces::camera::{Keyword, CAMERA_SPACES};
use crate::spaces::curves::ARRI_LOGC3_EIS;
use crate::spaces::display::{
    default_display_middle_gray_nits, pq_eotf, BT2408_GREY_NITS, BT2408_REF_WHITE_NITS, PQ_PEAK_PRESETS,
};
use crate::spaces::{CameraSpaceId, DisplayGamut, DisplayTransfer, InputSpace, LogCurve, OutputSpace};

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Confidence {
    None,
    Low,
    Medium,
    High,
}

#[derive(Debug, Clone, Serialize)]
pub struct Guess<T> {
    pub value: T,
    pub confidence: Confidence,
    /// 0–1, grows with the evidence margin over the runner-up.
    pub certainty: f64,
    pub reasons: Vec<String>,
    /// Other candidates with evidence, best first: (value, score).
    pub alternatives: Vec<(T, f64)>,
}

/// Where the detected spaces put 18% gray.
#[derive(Debug, Clone, Serialize)]
pub struct GrayProbe {
    pub input_code: f64,
    pub output_code: [f64; 3],
    pub output_nits: f64,
    pub expected_nits: f64,
    /// log2(output / expected display middle gray).
    pub stops_from_expected: f64,
}

#[derive(Debug, Clone, Serialize)]
pub struct Detection {
    pub input: Guess<InputSpace>,
    pub output_gamut: Guess<DisplayGamut>,
    pub output_transfer: Guess<DisplayTransfer>,
    pub probe: Option<GrayProbe>,
    /// Suggested display middle gray (cd/m²) when the name states a diffuse-white level
    /// (e.g. ARRI "DW100"): diffuse white × 26/203, the BT.2408 gray/white ratio.
    pub middle_gray_hint: Option<(f64, String)>,
    pub notes: Vec<String>,
}

impl Detection {
    pub fn output_space(&self) -> OutputSpace {
        OutputSpace::new(self.output_gamut.value, self.output_transfer.value)
    }
}

/// Normalised text forms used for matching.
struct Text {
    lower: String,
    /// lower-case, only [a-z0-9]: "ARRI_LogC4-to-Gamma24" → "arrilogc4togamma24"
    squashed: String,
    tokens: Vec<String>,
}

impl Text {
    fn new(lut: &Lut) -> Self {
        let mut s = String::new();
        if let Some(f) = &lut.filename {
            // drop the extension
            let stem = f.rsplit_once('.').map(|(a, _)| a).unwrap_or(f);
            s.push_str(stem);
            s.push(' ');
        }
        if let Some(t) = &lut.title {
            s.push_str(t);
            s.push(' ');
        }
        for c in &lut.comments {
            s.push_str(c);
            s.push(' ');
        }
        let lower = s.to_lowercase();
        // "davinci3d" is Resolve's export-format name, not a colour space.
        let lower = lower.replace("davinci3d", " ").replace("generated by resolve", " ");
        let squashed: String = lower.chars().filter(|c| c.is_ascii_alphanumeric()).collect();
        let tokens = lower
            .split(|c: char| !c.is_ascii_alphanumeric())
            .filter(|t| !t.is_empty())
            .map(str::to_string)
            .collect();
        Self { lower, squashed, tokens }
    }

    /// Keyword text starting with '=' must match a whole token; otherwise a substring
    /// of the squashed text.
    fn has(&self, k: &str) -> bool {
        match k.strip_prefix('=') {
            Some(t) => self.tokens.iter().any(|x| x == t),
            None => self.squashed.contains(k),
        }
    }

    /// Sum of matched keyword weights. A keyword that is a substring of another
    /// matched keyword in the same list is not counted twice ("709" inside "rec709").
    fn score(&self, kws: &[Keyword]) -> (f64, Vec<String>) {
        let matched: Vec<&Keyword> = kws
            .iter()
            .filter(|k| self.has(k.text) && !k.unless.iter().any(|u| self.has(u)))
            .collect();
        let mut total = 0.0;
        let mut why = Vec::new();
        for k in &matched {
            let bare = k.text.trim_start_matches('=');
            let shadowed = matched.iter().any(|o| {
                let ob = o.text.trim_start_matches('=');
                ob != bare && ob.contains(bare)
            });
            if !shadowed {
                total += k.weight;
                why.push(format!("“{bare}”"));
            }
        }
        (total, why)
    }
}

const fn kw(text: &'static str, weight: f64) -> Keyword {
    Keyword { text, weight, unless: &[] }
}
const fn kwu(text: &'static str, weight: f64, unless: &'static [&'static str]) -> Keyword {
    Keyword { text, weight, unless }
}

static GAMUT_KEYWORDS: &[(DisplayGamut, &[Keyword])] = &[
    (
        DisplayGamut::Rec709,
        &[kw("rec709", 4.0), kw("bt709", 4.0), kw("itu709", 4.0), kw("r709", 3.0), kw("709", 2.0), kw("video", 0.5)],
    ),
    (
        DisplayGamut::P3D65,
        &[kw("p3d65", 5.0), kw("d65p3", 5.0), kw("displayp3", 4.0), kwu("p3", 1.5, &["dci", "d60"])],
    ),
    (DisplayGamut::P3Dci, &[kw("p3dci", 5.0), kw("dcip3", 5.0), kwu("dci", 3.0, &["d65"])]),
    (
        DisplayGamut::Rec2020,
        &[
            kw("rec2020", 4.0),
            kw("bt2020", 4.0),
            kw("rec2100", 4.0),
            kw("bt2100", 4.0),
            kw("2100", 2.0),
            kw("=2020", 1.5),
        ],
    ),
];

#[derive(Clone, Copy, PartialEq)]
enum Tf {
    G22,
    G24,
    G26,
    Pq,
}

static TRANSFER_KEYWORDS: &[(Tf, &[Keyword])] = &[
    (Tf::Pq, &[kw("st2084", 5.0), kw("smpte2084", 5.0), kw("2084", 4.0), kw("=pq", 4.0), kw("hdr10", 3.0)]),
    (Tf::G24, &[kw("gamma24", 5.0), kw("=g24", 3.0), kw("709g24", 3.0), kw("bt1886", 4.0), kw("1886", 3.0)]),
    (Tf::G26, &[kw("gamma26", 5.0), kw("=g26", 3.0)]),
    (Tf::G22, &[kw("gamma22", 5.0), kw("=g22", 3.0), kw("709g22", 3.0), kw("srgb", 2.0)]),
];

fn level(top: f64, second: f64) -> (Confidence, f64) {
    let margin = top - second;
    let certainty = if top <= 0.0 { 0.0 } else { (1.0 - (-margin / 2.5).exp()).clamp(0.0, 1.0) };
    let c = if top >= 4.0 && margin >= 2.0 {
        Confidence::High
    } else if top >= 2.5 && margin >= 1.0 {
        Confidence::Medium
    } else if top > 0.0 {
        Confidence::Low
    } else {
        Confidence::None
    };
    (c, certainty)
}

fn rank<T: Copy>(mut scored: Vec<(T, f64, Vec<String>)>, default: T, what: &str) -> Guess<T> {
    // Stable sort keeps registry order for ties.
    scored.sort_by(|a, b| b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal));
    let top = scored.first().map(|s| s.1).unwrap_or(0.0);
    let second = scored.get(1).map(|s| s.1).unwrap_or(0.0);
    let (confidence, certainty) = level(top, second);
    if top <= 0.0 {
        return Guess {
            value: default,
            confidence,
            certainty,
            reasons: vec![format!("no {what} information found; using the default — please confirm")],
            alternatives: vec![],
        };
    }
    let best = &scored[0];
    let alternatives = scored[1..].iter().filter(|s| s.1 > 0.0).map(|s| (s.0, s.1)).collect();
    Guess { value: best.0, confidence, certainty, reasons: best.2.clone(), alternatives }
}

/// Gray probe for one input/output pairing.
pub fn gray_probe(lut: &Lut, input: &InputSpace, output: &OutputSpace, interp: Interpolation) -> GrayProbe {
    let code = input.curve().encode(0.18);
    let out = lut.apply(&Vec3::new(code, code, code), interp);
    let lin = output.decode(&out);
    let nits = (output.rgb_to_xyz() * lin).y;
    let expected = default_display_middle_gray_nits(output);
    GrayProbe {
        input_code: code,
        output_code: [out.x, out.y, out.z],
        output_nits: nits,
        expected_nits: expected,
        stops_from_expected: (nits.max(1e-6) / expected).log2(),
    }
}

pub fn detect(lut: &Lut) -> Detection {
    let text = Text::new(lut);
    let mut notes = Vec::new();

    // ---------------- output gamut ----------------
    let gamut_scored: Vec<_> = GAMUT_KEYWORDS
        .iter()
        .map(|(g, kws)| {
            let (s, why) = text.score(kws);
            (*g, s, why.into_iter().map(|w| format!("{w} in name/metadata")).collect())
        })
        .collect();
    let output_gamut = rank(gamut_scored, DisplayGamut::Rec709, "display gamut");

    // ---------------- output transfer ----------------
    let bare_gamma = |a: char, b: char| {
        Regex::new(&format!(r"(?:^|[^0-9.]){a}[.\-]{b}(?:$|[^0-9.])"))
            .unwrap()
            .is_match(&text.lower)
    };
    let (_, out_max) = lut.output_extent();
    let mut tf_scored: Vec<(Tf, f64, Vec<String>)> = TRANSFER_KEYWORDS
        .iter()
        .map(|(t, kws)| {
            let (s, why) = text.score(kws);
            (*t, s, why.into_iter().map(|w| format!("{w} in name/metadata")).collect::<Vec<_>>())
        })
        .collect();
    for (tf, a, b) in [(Tf::G22, '2', '2'), (Tf::G24, '2', '4'), (Tf::G26, '2', '6')] {
        if bare_gamma(a, b) {
            let e = tf_scored.iter_mut().find(|e| e.0 == tf).unwrap();
            e.1 += 3.0;
            e.2.push(format!("“{a}.{b}” / “{a}-{b}” in name"));
        }
    }
    if out_max < 0.80 {
        let e = tf_scored.iter_mut().find(|e| e.0 == Tf::Pq).unwrap();
        e.1 += 2.0;
        e.2.push(format!("LUT output never exceeds {out_max:.3} (≈{:.0} nits if PQ)", pq_eotf(out_max)));
    }
    // Weak priors from the gamut when the name says nothing about the transfer.
    let tf_top = tf_scored.iter().map(|e| e.1).fold(0.0, f64::max);
    if tf_top == 0.0 {
        let (tf, why) = match output_gamut.value {
            DisplayGamut::Rec709 => (Tf::G24, "Rec.709 deliverables are usually gamma 2.4 (BT.1886)"),
            DisplayGamut::P3Dci => (Tf::G26, "P3-DCI implies cinema gamma 2.6"),
            DisplayGamut::P3D65 => (Tf::G26, "P3-D65 is most often gamma 2.6"),
            DisplayGamut::Rec2020 => (Tf::Pq, "Rec.2020/2100 is most often PQ"),
        };
        let e = tf_scored.iter_mut().find(|e| e.0 == tf).unwrap();
        e.1 += 1.0;
        e.2.push(why.to_string());
    }

    let pq_peak = detect_pq_peak(&text, out_max);
    let to_transfer = |t: Tf| match t {
        Tf::G22 => DisplayTransfer::Gamma { gamma: 2.2 },
        Tf::G24 => DisplayTransfer::Gamma { gamma: 2.4 },
        Tf::G26 => DisplayTransfer::Gamma { gamma: 2.6 },
        Tf::Pq => DisplayTransfer::Pq { peak_nits: pq_peak.0 },
    };
    let tf_guess = rank(tf_scored, Tf::G24, "display transfer");
    let mut output_transfer = Guess {
        value: to_transfer(tf_guess.value),
        confidence: tf_guess.confidence,
        certainty: tf_guess.certainty,
        reasons: tf_guess.reasons,
        alternatives: tf_guess.alternatives.into_iter().map(|(t, s)| (to_transfer(t), s)).collect(),
    };
    if output_transfer.value.is_hdr() {
        output_transfer.reasons.push(pq_peak.1.clone());
    } else if out_max < 0.80 {
        notes.push(format!(
            "Output never exceeds {out_max:.3} although the name suggests gamma — check the output transfer."
        ));
    }
    if text.has("hlg") || text.has("=b67") {
        notes.push("Name mentions HLG, which is not supported; choose the closest output manually.".into());
    }

    let output = OutputSpace::new(output_gamut.value, output_transfer.value);

    // ---------------- input (camera) ----------------
    let ei = detect_ei(&text);
    let mut cam_scored: Vec<(InputSpace, f64, Vec<String>)> = CAMERA_SPACES
        .iter()
        .map(|cs| {
            let (s, why) = text.score(cs.keywords);
            let mut input = InputSpace::new(cs.id);
            if let (LogCurve::ArriLogC3 { .. }, Some(ei)) = (cs.curve, ei) {
                input.arri_ei = ei;
            }
            (input, s, why.into_iter().map(|w| format!("{w} in name/metadata")).collect())
        })
        .collect();
    let any_text = cam_scored.iter().any(|c| c.1 > 0.0);
    if lut.is_3d() {
        for c in cam_scored.iter_mut() {
            if any_text && c.1 <= 0.0 {
                continue;
            }
            let p = gray_probe(lut, &c.0, &output, Interpolation::Tetrahedral);
            let w = 1.5 * (1.0 - p.stops_from_expected.abs() / 1.5).max(0.0);
            if w > 0.0 {
                c.1 += w;
                c.2.push(format!(
                    "its 18% gray lands {:+.2} stops from display middle gray",
                    p.stops_from_expected
                ));
            } else if any_text {
                c.2.push(format!(
                    "but its 18% gray lands {:+.2} stops from display middle gray",
                    p.stops_from_expected
                ));
            }
        }
    }
    let mut input = rank(cam_scored, InputSpace::new(CameraSpaceId::ArriLogC4Awg4), "camera");
    if !any_text {
        input.confidence = Confidence::None;
        input.reasons.insert(
            0,
            "no camera named in file name or metadata; best guess from where 18% gray lands — please confirm".into(),
        );
    }
    if let (LogCurve::ArriLogC3 { .. }, Some(ei)) = (input.value.def().curve, ei) {
        input.reasons.push(format!("EI {ei} in name"));
    } else if matches!(input.value.def().curve, LogCurve::ArriLogC3 { .. }) {
        input.reasons.push("EI not stated; assuming EI 800".into());
    }

    // ---------------- range notes ----------------
    if text.squashed.contains("fullinfullout") || text.squashed.contains("fullrange") {
        notes.push("Metadata says full-range in/out.".into());
    }
    if text.squashed.contains("legal") || text.squashed.contains("videorange") || text.squashed.contains("smpterange") {
        notes.push("Metadata mentions legal/video range — check the range setting.".into());
    }
    notes.extend(lut.warnings.iter().cloned());
    if !lut.is_3d() {
        notes.push("1D LUT: it cannot change colour beyond per-channel curves; the fit will be near-diagonal in camera RGB.".into());
    }

    let middle_gray_hint = detect_diffuse_white(&text).map(|dw| {
        let g = dw * BT2408_GREY_NITS / BT2408_REF_WHITE_NITS;
        (g, format!("“DW{dw:.0}” in name: diffuse white {dw:.0} nits → middle gray ≈ {g:.1} nits"))
    });

    let probe = lut.is_3d().then(|| gray_probe(lut, &input.value, &output, Interpolation::Tetrahedral));

    Detection { input, output_gamut, output_transfer, probe, middle_gray_hint, notes }
}

fn detect_diffuse_white(text: &Text) -> Option<f64> {
    let re = Regex::new(r"(?:^|[^a-z])dw[\s_\-]?(\d{2,4})(?:$|[^0-9])").unwrap();
    let v: f64 = re.captures(&text.lower)?[1].parse().ok()?;
    (50.0..=1000.0).contains(&v).then_some(v)
}

fn detect_ei(text: &Text) -> Option<u16> {
    let re = Regex::new(r"(?:^|[^a-z])ei[\s_\-]?(\d{3,4})|(\d{3,4})[\s_\-]?ei(?:$|[^a-z])").unwrap();
    let found = re.captures_iter(&text.lower).find_map(|c| {
        let v: u16 = c.get(1).or(c.get(2))?.as_str().parse().ok()?;
        ARRI_LOGC3_EIS.contains(&v).then_some(v)
    });
    found
}

/// (peak nits, reason)
fn detect_pq_peak(text: &Text, out_max: f64) -> (f64, String) {
    let nits = Regex::new(r"(\d{3,5})[\s_\-]?nits?").unwrap();
    if let Some(c) = nits.captures(&text.lower) {
        if let Ok(v) = c[1].parse::<f64>() {
            if (100.0..=10000.0).contains(&v) {
                return (v, format!("peak {v:.0} nits from name"));
            }
        }
    }
    let k = Regex::new(r"(?:2084|pq|hdr)[\s_\-]*(\d{1,2}(?:\.\d)?)k(?:$|[^a-z0-9])").unwrap();
    if let Some(c) = k.captures(&text.lower) {
        if let Ok(v) = c[1].parse::<f64>() {
            let v = v * 1000.0;
            if (100.0..=10000.0).contains(&v) {
                return (v, format!("peak {v:.0} nits from “{}k” in name", &c[1]));
            }
        }
    }
    let est = pq_eotf(out_max.min(1.0));
    let snapped = PQ_PEAK_PRESETS
        .iter()
        .copied()
        .min_by(|a, b| (a - est).abs().partial_cmp(&(b - est).abs()).unwrap())
        .unwrap();
    if (snapped - est).abs() / snapped < 0.15 {
        (snapped, format!("peak ≈{est:.0} nits from LUT output range → {snapped:.0}"))
    } else {
        (1000.0, format!("peak not stated; LUT reaches ≈{est:.0} nits; assuming 1000"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lut::{Lut, Lut3D, LutFormat};

    fn named(name: &str) -> Lut {
        Lut {
            format: LutFormat::Cube,
            filename: Some(name.into()),
            title: None,
            comments: vec![],
            shaper: None,
            cube: Some(Lut3D::from_fn(2, |v| v)),
            warnings: vec![],
        }
    }

    #[test]
    fn arri_official_names() {
        let d = detect(&named("ARRI_LogC4-to-Gamma24_Rec709-D65_v1-65.cube"));
        assert_eq!(d.input.value.id, CameraSpaceId::ArriLogC4Awg4);
        assert_eq!(d.input.confidence, Confidence::High);
        assert_eq!(d.output_gamut.value, DisplayGamut::Rec709);
        assert_eq!(d.output_transfer.value, DisplayTransfer::Gamma { gamma: 2.4 });

        let d = detect(&named("ARRI_LogC4-to-Gamma26_P3-DCI_v1-65.cube"));
        assert_eq!(d.output_gamut.value, DisplayGamut::P3Dci);
        assert_eq!(d.output_transfer.value, DisplayTransfer::Gamma { gamma: 2.6 });

        let d = detect(&named("ARRI_LogC4-to-St2084_1K_Rec2100-D65_DW100_v1_65.cube"));
        assert_eq!(d.output_gamut.value, DisplayGamut::Rec2020);
        assert_eq!(d.output_transfer.value, DisplayTransfer::Pq { peak_nits: 1000.0 });
        assert!((d.middle_gray_hint.unwrap().0 - 100.0 * 26.0 / 203.0).abs() < 1e-9);

        let d = detect(&named("ARRI_LogC4-to-St2084-1K_P3-D65_DW100_v1-65.cube"));
        assert_eq!(d.output_gamut.value, DisplayGamut::P3D65);
        assert_eq!(d.output_transfer.value, DisplayTransfer::Pq { peak_nits: 1000.0 });
    }

    #[test]
    fn other_vendors() {
        let cases = [
            ("SLog3SGamut3.Cine_To_Rec709.cube", CameraSpaceId::SonySLog3SGamut3Cine),
            ("S-Log3_S-Gamut3_to_709.cube", CameraSpaceId::SonySLog3SGamut3),
            ("RWG_Log3G10 to REC709_BT1886.cube", CameraSpaceId::RedLog3G10Rwg),
            ("CanonLog3_CinemaGamut_to_BT709.cube", CameraSpaceId::CanonLog3CinemaGamut),
            ("Canon Log 2 to 709.cube", CameraSpaceId::CanonLog2CinemaGamut),
            ("VLog_to_V709.cube", CameraSpaceId::PanasonicVLogVGamut),
            ("Blackmagic Gen 5 Film to Video.cube", CameraSpaceId::BmdFilmGen5),
            ("F-Log2_to_BT709.cube", CameraSpaceId::FujiFLog2FGamut),
            ("F-Log_to_BT709.cube", CameraSpaceId::FujiFLogFGamut),
            ("DWG_DI_to_Rec709.cube", CameraSpaceId::DaVinciIntermediateDwg),
            ("ACEScct_to_P3D65.cube", CameraSpaceId::AcesCctAp1),
            ("ACES2065_to_Print_709G24.cube", CameraSpaceId::Aces2065Ap0),
            ("ACES2065-1_AP0_to_Rec709.cube", CameraSpaceId::Aces2065Ap0),
            ("AlexaV3_LookA_LogC2Video_Rec709_EE_davinci3d.cube", CameraSpaceId::ArriLogC3Awg3),
        ];
        for (name, want) in cases {
            assert_eq!(detect(&named(name)).input.value.id, want, "{name}");
        }
    }

    #[test]
    fn ei_and_ambiguity() {
        let d = detect(&named("LogC3_EI1280_to_709.cube"));
        assert_eq!(d.input.value.arri_ei, 1280);
        let d = detect(&named("SLog3_to_709.cube"));
        assert!(d.input.confidence <= Confidence::Low, "S-Log3 alone is ambiguous between gamuts");
        let d = detect(&named("mylook_v2.cube"));
        assert_eq!(d.input.confidence, Confidence::None);
    }
}
