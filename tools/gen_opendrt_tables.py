#!/usr/bin/env python3
"""Generate crates/lutmatrix-opendrt/src/tables.rs from the bundled OpenDRT DCTL.

    python3 tools/gen_opendrt_tables.py

Everything numeric in the Rust port that comes from the DCTL (look and tonescale presets,
parameter ranges, gamut/CAT matrices, combo-box labels) is generated here rather than
typed, and `cargo test -p lutmatrix-opendrt` re-parses the DCTL to check the result.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRATE = os.path.join(ROOT, "crates", "lutmatrix-opendrt")
SRC = open(os.path.join(CRATE, "opendrt", "OpenDRT_v1.1.0.1.dctl")).read()


def num(s):
    """A C float literal as a Rust f32 literal (same decimal digits, so same rounding)."""
    s = s.strip().rstrip("f")
    if not re.search(r"[.eE]", s):
        s += ".0"
    return s


def combo(name):
    m = re.search(r"^DEFINE_UI_PARAMS\(" + name + r", [^,]*, DCTLUI_COMBO_BOX, \d+, \{[^}]*\}, \{([^}]*)\}\)", SRC, re.M)
    return [x.strip() for x in m.group(1).split(",")]


def blocks(var):
    out = []
    for m in re.finditer(r"if \(" + var + r"==(\d+)\) \{ // ([^\n]*)\n\s*(.*?);\n", SRC):
        idx, label, body = m.groups()
        vals = [[x.strip() for x in a.split("=")] for a in body.split(",")]
        out.append((int(idx), label.strip(), vals))
    return out


# Look parameters in preset order, with the stickshift slider ranges.
looks = blocks("look_preset")
order = [k for k, _ in looks[0][2]]
ranges = {}
for m in re.finditer(r"^// DEFINE_UI_PARAMS\(_(\w+), ([^,]*), (\w+), ([^,)]*)(?:, ([^)]*))?\)", SRC, re.M):
    name, _label, kind, _default, rest = m.groups()
    if kind == "DCTLUI_SLIDER_FLOAT":
        lo, hi = rest.split(",")[:2]
        ranges[name] = ("Float", num(lo), num(hi))
    elif kind == "DCTLUI_CHECK_BOX":
        ranges[name] = ("Toggle", "0.0", "1.0")
    else:
        n = len(re.match(r"\{([^}]*)\}", rest).group(1).split(","))
        ranges[name] = ("Choice", "0.0", f"{n - 1}.0")

out = ["// @generated by tools/gen_opendrt_tables.py from opendrt/OpenDRT_v1.1.0.1.dctl. Do not edit.",
       "// OpenDRT (c) Jed Smith, GPLv3. https://github.com/jedypod/open-display-transform",
       "#![allow(clippy::excessive_precision, clippy::approx_constant)]",
       "", "use serde::{Deserialize, Serialize};", "", "use crate::params::{Kind, ParamInfo};", "use crate::M3;", ""]

def struct(name, doc, fields):
    n = len(fields)
    out.append(doc)
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]")
    out.append(f"pub struct {name} {{")
    out.extend(f"    pub {k}: f32," for k in fields)
    out.append("}\n")
    out.append(f"impl {name} {{")
    out.append(f"    /// The fields in declaration (DCTL) order.")
    out.append(f"    pub fn to_array(&self) -> [f32; {n}] {{")
    out.append("        [" + ", ".join(f"self.{k}" for k in fields) + "]")
    out.append("    }\n")
    out.append(f"    /// Inverse of [`{name}::to_array`].")
    out.append(f"    pub fn from_array(a: &[f32; {n}]) -> Self {{")
    out.append("        Self { " + ", ".join(f"{k}: a[{i}]" for i, k in enumerate(fields)) + " }")
    out.append("    }")
    out.append("}\n")

struct("LookParams", "/// Every per-look OpenDRT parameter (the DCTL's stickshift set). Toggles and the creative\n/// white index are stored as numbers: a toggle is on when non-zero, `cwp` is rounded.", order)
out.append("/// Every look parameter, in the order of the DCTL's look presets, with the stickshift")
out.append("/// slider range (`Choice`/`Toggle`: index range).")
out.append("pub const LOOK_PARAMS: [ParamInfo; %d] = [" % len(order))
for k in order:
    kind, lo, hi = ranges[k]
    out.append(f'    ParamInfo {{ name: "{k}", kind: Kind::{kind}, min: {lo}, max: {hi} }},')
out.append("];\n")

out.append("/// Look presets (`look_preset` combo box), index = combo index.")
out.append("pub const LOOK_PRESETS: [(&str, LookParams); %d] = [" % len(looks))
for i, (idx, label, vals) in enumerate(looks):
    assert idx == i and [k for k, _ in vals] == order, label
    fields = ", ".join(f"{k}: {num(v)}" for k, v in vals)
    out.append(f'    ("{label}", LookParams {{ {fields} }}),')
out.append("];\n")

tones = blocks("tonescale_preset")
tone_order = [k for k, _ in tones[0][2]]
struct("ToneParams", "/// The subset of [`LookParams`] a tonescale preset overrides.", tone_order)
out.append("impl ToneParams {")
out.append("    /// Overwrite the tonescale fields of `look`.")
out.append("    pub fn apply_to(&self, look: &mut LookParams) {")
out.extend(f"        look.{k} = self.{k};" for k in tone_order)
out.append("    }")
out.append("}\n")
out.append("/// Tonescale presets (`tonescale_preset` combo box); index 0 (USE LOOK PRESET) has no")
out.append("/// entry, so entry `i` is combo index `i + 1`.")
out.append("pub const TONESCALE_PRESETS: [(&str, ToneParams); %d] = [" % len(tones))
for i, (idx, label, vals) in enumerate(tones):
    assert idx == i + 1 and [k for k, _ in vals] == tone_order, label
    fields = ", ".join(f"{k}: {num(v)}" for k, v in vals)
    out.append(f'    ("{label}", ToneParams {{ {fields} }}),')
out.append("];\n")

for name in ["in_gamut", "in_oetf", "look_preset", "tonescale_preset", "_cwp", "display_encoding_preset"]:
    labels = combo(name)
    const = name.strip("_").upper() + "_LABELS"
    out.append(f"pub const {const}: [&str; {len(labels)}] = [" + ", ".join(f'"{l}"' for l in labels) + "];")
out.append("")

for m in re.finditer(r"^#define (matrix_\w+) make_float3x3\((.*)\)\s*$", SRC, re.M):
    name, body = m.groups()
    rows = re.findall(r"make_float3\(([^)]*)\)", body)
    assert len(rows) == 3
    rs = ", ".join("[" + ", ".join(num(v) for v in r.split(",")) + "]" for r in rows)
    out.append(f"pub const {name.upper()}: M3 = [{rs}];")
out.append("")

path = os.path.join(CRATE, "src", "tables.rs")
open(path, "w").write("\n".join(out))
print("wrote", path)
